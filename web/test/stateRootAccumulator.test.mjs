// THE SHARED VECTORS. This Verify view's check is the FOURTH implementation of the state root accumulator proof, independent of the other three on purpose (the node's
// pkg/rootaccum, which makes the proofs, infrix-verify's stateroot package, which verifykit uses, and @infrix/verify's, which the SDK ships). ONE file of vectors,
// generated by the Infrix runtime, pins all four; this test holds this implementation to its copy and pins the copy's SHA-256, so no copy can be edited alone: change the runtime's implementation and its
// vectors change, the runtime's tests demand the new file be committed there, and this pin fails here until the new file is copied over and the pin updated
// deliberately, in the same commit as whatever makes this implementation agree with it.
//
// VECTORS_SHA256 is over the file with line endings normalised to LF (a Windows checkout may rewrite them).
const VECTORS_SHA256 = 'e1c5b1b073a3cbf8608913c1a21e33929d686330e95d9329037bdfcdf2bf4a07';

function loadVectors() {
  const raw = readFileSync(path.join(here, '..', '..', 'testdata', 'state-root-vectors.json'), 'utf8');
  const sum = createHash('sha256').update(raw.replace(/\r\n/g, '\n')).digest('hex');
  assert.equal(
    sum,
    VECTORS_SHA256,
    'testdata/state-root-vectors.json is not the file this repository pins: the vectors are generated by the Infrix runtime (pkg/rootaccum) and copied here whole; ' +
      'if they changed on purpose, copy the new file and update the pin in the same commit as the change that makes this implementation agree',
  );
  return JSON.parse(raw);
}

const hex = (s) => Uint8Array.from(s.match(/../g).map((b) => parseInt(b, 16)));
const toHex = (b) => Array.from(b, (x) => x.toString(16).padStart(2, '0')).join('');
const paths = (p) => (p ?? []).map(hex);

test('every leaf hash and every consumer digest of the vectors is reproduced, and the two leaf kinds never hash alike', async () => {
  const vf = loadVectors();
  assert.equal(vf.consumerDomain, 'infrix-root-consumer-v1');
  let consumers = 0;
  for (const [i, l] of vf.leaves.entries()) {
    const got = await stateRootLeafHash(l.height, hex(l.root), l.consumer ?? '');
    assert.equal(toHex(got), l.leafHash, `leaf ${i}`);
    if (l.consumer) {
      consumers++;
      assert.equal(toHex(await consumerDigest(l.consumer)), l.consumerDigest, `the digest of leaf ${i}'s consumer`);
      assert.notEqual(toHex(await stateRootLeafHash(l.height, hex(l.root), '')), l.leafHash, `leaf ${i}: a consumer leaf and a root-change leaf of the same height and root hash alike`);
    }
  }
  assert.equal(consumers, 10, 'the 10 consumer leaves the runtime generates');
});

test('every audit path of every tree size to forty computes the seal the vectors name', async () => {
  const vf = loadVectors();
  assert.equal(vf.trees.length, 40, 'the vectors hold every tree size 1..40');
  let proofs = 0;
  for (const tree of vf.trees) {
    assert.equal(tree.proofs.length, tree.size, `size ${tree.size} has one proof per leaf`);
    for (const p of tree.proofs) {
      const leaf = vf.leaves[p.index];
      const consumer = leaf.consumer ?? '';
      const got = await sealedRootOf(p.index, tree.size, leaf.height, hex(leaf.root), consumer, paths(p.path));
      assert.equal(toHex(got), tree.sealed, `size ${tree.size} leaf ${p.index}`);
      // a tampered copy of the same proof must not compute the same seal
      if ((p.path ?? []).length > 0) {
        const bad = paths(p.path);
        bad[0][0] ^= 1;
        let same = false;
        try {
          same = toHex(await sealedRootOf(p.index, tree.size, leaf.height, hex(leaf.root), consumer, bad)) === tree.sealed;
        } catch {
          same = false;
        }
        assert.equal(same, false, `size ${tree.size} leaf ${p.index}: a flipped sibling computes the same seal`);
      }
      // a consumer leaf proves only for its own consumer
      if (consumer) {
        for (const other of [`${consumer}x`, '']) {
          let same = false;
          try {
            same = toHex(await sealedRootOf(p.index, tree.size, leaf.height, hex(leaf.root), other, paths(p.path))) === tree.sealed;
          } catch {
            same = false;
          }
          assert.equal(same, false, `size ${tree.size} leaf ${p.index}: the leaf proves for consumer "${other}"`);
        }
      }
      proofs++;
    }
  }
  assert.equal(proofs, (40 * 41) / 2, 'every leaf of every size');
});

async function consistencyResult(c, path) {
  try {
    return await verifyConsistency(c.first, c.second, hex(c.firstMth), path);
  } catch {
    return null;
  }
}

test('every consistency proof of every pair of sizes to forty verifies, and every tamper of it is refused', async () => {
  const vf = loadVectors();
  assert.equal(vf.consistency.length, (40 * 41) / 2, 'every pair 1 <= first <= second <= 40');
  for (const c of vf.consistency) {
    const firstSealed = vf.trees[c.first - 1].sealed;
    const secondSealed = vf.trees[c.second - 1].sealed;
    assert.equal(toHex(await stateRootSeal(c.first, hex(c.firstMth))), firstSealed, `(${c.first},${c.second}): the first hash seals to the first tree`);
    const path = paths(c.path);
    const second = await consistencyResult(c, path);
    assert.ok(second, `(${c.first},${c.second}): the proof does not verify`);
    assert.equal(toHex(await stateRootSeal(c.second, second)), secondSealed, `(${c.first},${c.second}): the second tree's seal`);
    if (path.length > 0) {
      const flipped = path.map((p) => Uint8Array.from(p));
      flipped[flipped.length - 1][5] ^= 0x80;
      const f = await consistencyResult(c, flipped);
      assert.ok(f === null || toHex(await stateRootSeal(c.second, f)) !== secondSealed, `(${c.first},${c.second}): a flipped last element still proves`);
      const dropped = await consistencyResult(c, path.slice(1));
      assert.ok(dropped === null || toHex(await stateRootSeal(c.second, dropped)) !== secondSealed, `(${c.first},${c.second}): a dropped first element still proves`);
      if (path.length >= 2) {
        assert.equal(await consistencyResult(c, path.slice(0, -1)), null, `(${c.first},${c.second}): a proof missing its last element verified`);
      }
    }
    // an extra element is refused whether the sizes differ or are equal (equal sizes need an EMPTY proof)
    assert.equal(await consistencyResult(c, [...path, new Uint8Array(32).fill(9)]), null, `(${c.first},${c.second}): a proof with an extra element verified`);
    const wrong = hex(c.firstMth);
    wrong[0] ^= 1;
    let w = null;
    try {
      w = await verifyConsistency(c.first, c.second, wrong, path);
    } catch {
      w = null;
    }
    assert.ok(w === null || toHex(await stateRootSeal(c.second, w)) !== secondSealed, `(${c.first},${c.second}): a first hash that is not the first tree's proves the second tree's seal`);
  }
  // a first tree larger than the second is no prefix of it for any proof shape, and an empty first tree proves nothing
  for (const [a, b] of [[2, 1], [4, 3], [8, 5], [4, 1], [3, 2]]) {
    for (const path of [[], [new Uint8Array(32).fill(2)]]) {
      await assert.rejects(() => verifyConsistency(a, b, new Uint8Array(32).fill(1), path), undefined, `(${a},${b}) verified`);
    }
  }
  await assert.rejects(() => verifyConsistency(0, 4, new Uint8Array(32), []), undefined, 'an empty first tree verified');
});

function readerFor(c) {
  if (c.noReader) return null;
  return {
    async anchorAt(tx) {
      if (c.anchorError) throw new Error(c.anchorError);
      const entry = (c.anchors ?? {})[tx];
      if (!entry) throw new Error('no such transaction');
      return entry;
    },
  };
}

test('every document case of the vectors gets its verdict', async () => {
  const vf = loadVectors();
  assert.ok(vf.documents.length >= 40, 'the vectors hold the document cases');
  const seen = new Set();
  for (const c of vf.documents) {
    const doc = c.document === undefined ? null : c.document;
    const res = await checkStateRootProof(doc, hex(c.bundleRoot), c.consumerId ?? '', readerFor(c));
    assert.equal(res.verdict, c.verdict, `${c.name}: ${res.verdict} (${res.detail}), want ${c.verdict}`);
    for (const want of c.detailContains) {
      assert.ok(res.detail.includes(want), `${c.name}: detail "${res.detail}" does not contain "${want}"`);
    }
    seen.add(c.verdict);
  }
  assert.deepEqual([...seen].sort(), ['fail', 'pass', 'skip'], 'the vectors exercise every outcome');
});

const passing = () => {
  const c = loadVectors().documents.find((d) => d.name === 'a proven leaf recorded in the gap of a delayed anchor passes');
  assert.ok(c, 'the vectors have the passing delayed-anchor case');
  return c;
};

test('a version 1 document that carries a consumer, and a status the verifier does not know, are skips and never a pass', async () => {
  const c = passing();
  assert.equal((await checkStateRootProof(c.document, hex(c.bundleRoot), c.consumerId, readerFor(c))).verdict, 'pass', 'premise');
  const v1 = await checkStateRootProof({ ...c.document, version: 'infrix-state-root-proof-v1' }, hex(c.bundleRoot), c.consumerId, readerFor(c));
  assert.equal(v1.verdict, 'skip');
  assert.match(v1.detail, /no consumer recorded/);
  const odd = await checkStateRootProof({ ...c.document, status: 'bogus' }, hex(c.bundleRoot), c.consumerId, readerFor(c));
  assert.equal(odd.verdict, 'skip');
  assert.match(odd.detail, /does not read/);
});

test('a prior whose listed root is not the seal of its size and hash is refused even when L0 lists that root', async () => {
  const c = passing();
  const other = new Uint8Array(32).fill(0xfe);
  const priorTx = c.document.prior.anchor.txHash;
  const anchors = { ...c.anchors, [priorTx]: { ...c.anchors[priorTx], roots: [...c.anchors[priorTx].roots, toHex(other)] } };
  const forged = { ...c.document, prior: { ...c.document.prior, accumulatorRoot: toHex(other) } };
  const res = await checkStateRootProof(forged, hex(c.bundleRoot), c.consumerId, readerFor({ anchors }));
  assert.equal(res.verdict, 'fail');
  assert.match(res.detail, /not shown to be a prefix/);
});

test('a reader that offers only the roots (no window) never gets a pass: the leaf is undated', async () => {
  const c = passing();
  const rootsOnly = { async rootsAt(tx) { return c.anchors[tx].roots; } };
  const res = await checkStateRootProof(c.document, hex(c.bundleRoot), c.consumerId, rootsOnly);
  assert.equal(res.verdict, 'skip');
  assert.match(res.detail, /undated/);
});

// ---- the check over an exported file, as `verify` reads it ----

const bundleRoot = Uint8Array.from({ length: 32 }, (_, i) => (i === 0 ? 3 : 0));
const pkgOf = (stateRoot, outcomeId = 'outcome-x') => ({ version: '1', bundleData: JSON.stringify({ stateRoot: Array.from(stateRoot), outcomeId }) });

test('a file with no sibling document is a skip, and a required proof that is absent is a failure', async () => {
  const none = await verifyStateRootOfExport(pkgOf(bundleRoot), null);
  assert.equal(none.name, STATE_ROOT_CHECK_NAME);
  assert.equal(none.verdict, 'skip');
  assert.match(none.detail, /no state root proof is attached/);
  const required = await verifyStateRootOfExport(pkgOf(bundleRoot), null, { require: true });
  assert.equal(required.verdict, 'fail');
  assert.match(required.detail, /a proven state root is required/);
});

test('the document is read beside a bare or an enveloped package, bound to the package\'s own outcome id', async () => {
  const c = passing();
  const root = hex(c.bundleRoot);
  for (const file of [
    { ...pkgOf(root, c.consumerId), [STATE_ROOT_DOCUMENT_KEY]: c.document },
    { bundle: pkgOf(root, c.consumerId), [STATE_ROOT_DOCUMENT_KEY]: c.document },
  ]) {
    const pkg = file.bundleData !== undefined ? file : file.bundle;
    assert.deepEqual(Array.from(bundleStateRoot(pkg)), Array.from(root));
    assert.equal(bundleConsumerId(pkg), c.consumerId);
    const res = await verifyStateRootOfExport(file, readerFor(c));
    assert.equal(res.verdict, 'pass', res.detail);
    // the same file with no endpoint holds but is not confirmed
    const offline = await verifyStateRootOfExport(file, null);
    assert.equal(offline.verdict, 'skip');
    assert.match(offline.detail, /no L0 endpoint was supplied/);
  }
  assert.equal(STATE_ROOT_DOCUMENT_VERSION, c.document.version);
});

test('a proof for another root, or recorded for another outcome, than the package carries is a failure over the whole file', async () => {
  const c = passing();
  const forged = hex(c.bundleRoot);
  forged[0] ^= 0xff;
  const wrongRoot = await verifyStateRootOfExport({ ...pkgOf(forged, c.consumerId), [STATE_ROOT_DOCUMENT_KEY]: c.document }, readerFor(c));
  assert.equal(wrongRoot.verdict, 'fail');
  assert.match(wrongRoot.detail, /the proof is for state root/);
  const wrongOutcome = await verifyStateRootOfExport({ ...pkgOf(hex(c.bundleRoot), `${c.consumerId}-other`), [STATE_ROOT_DOCUMENT_KEY]: c.document }, readerFor(c));
  assert.equal(wrongOutcome.verdict, 'fail');
  assert.match(wrongOutcome.detail, /is not this bundle's/);
  const anonymous = await verifyStateRootOfExport({ ...pkgOf(hex(c.bundleRoot), ''), [STATE_ROOT_DOCUMENT_KEY]: c.document }, readerFor(c));
  assert.equal(anonymous.verdict, 'skip');
  assert.match(anonymous.detail, /no consumer to bind/);
});

test('the Verify view appends the check: a failure fails the verification, a skip is shown as unchecked and leaves the verdict, a proof with no endpoint holds but is unconfirmed', async () => {
  const c = passing();
  const root = hex(c.bundleRoot);
  const base = { passed: true, checks: [{ name: 'version', passed: true }] };
  const withDoc = { ...pkgOf(root, c.consumerId), [STATE_ROOT_DOCUMENT_KEY]: c.document };

  const none = await appendStateRootCheck(base, pkgOf(root, c.consumerId));
  assert.equal(none.passed, true, 'a file with no document leaves the verdict where it was');
  assert.equal(none.checks.length, 2);
  assert.equal(none.checks[1].name, STATE_ROOT_CHECK_NAME);
  assert.equal(none.checks[1].passed, true);
  assert.match(none.checks[1].detail, /^unchecked: no state root proof is attached/);

  const offline = await appendStateRootCheck(base, withDoc, null);
  assert.equal(offline.passed, true);
  assert.match(offline.checks[1].detail, /^unchecked: .*no L0 endpoint was supplied/, 'the browser has no batch-entry reader, so a proven document is checked and unconfirmed');

  const confirmed = await appendStateRootCheck(base, withDoc, readerFor(c));
  assert.equal(confirmed.passed, true);
  assert.equal(confirmed.checks[1].passed, true);
  assert.doesNotMatch(confirmed.checks[1].detail, /^unchecked/);

  const forged = hex(c.bundleRoot);
  forged[0] ^= 0xff;
  const failed = await appendStateRootCheck(base, { ...pkgOf(forged, c.consumerId), [STATE_ROOT_DOCUMENT_KEY]: c.document }, readerFor(c));
  assert.equal(failed.passed, false, 'a forged root fails the whole verification');
  assert.equal(failed.checks[1].passed, false);

  const required = await appendStateRootCheck(base, pkgOf(root, c.consumerId), null, { require: true });
  assert.equal(required.passed, false, 'a required proof that is absent fails');
  // the input result is not mutated
  assert.equal(base.checks.length, 1);
});
