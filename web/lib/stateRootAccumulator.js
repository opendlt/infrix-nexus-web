// Nexus — the state root accumulator check (native, offline), the Verify view's own copy.
//
// WHY. An evidence bundle carries the node's state root as of its own finalization. The node anchors its state root only every N canonical blocks (and only when it
// changed), so almost no bundle's root is a root any anchor names, and a verifier that demanded it be the anchored root would refuse nearly every honest bundle. The
// node therefore keeps an append-only Merkle tree of every root it held and of every consumption of one, anchors the sealed root of that tree, and an exported bundle
// carries an inclusion proof of ITS leaf against an anchored seal. A root the node never held is in no anchored seal, and a leaf recorded for another bundle is not
// this bundle's.
//
// THE TREE is the RFC 9162 Merkle tree over two kinds of leaf, told apart by the length of what they hash:
//
//   a root-change leaf  SHA-256(0x00 || be64(height) || root)                       40 bytes of leaf data
//   a consumer leaf     SHA-256(0x00 || be64(height) || root || consumerDigest)     72 bytes of leaf data
//   consumerDigest      SHA-256("infrix-root-consumer-v1" || utf8(id))
//
// and node = SHA-256(0x01 || left || right), a node over n leaves splitting at the largest power of two below n. The SEALED ROOT the node anchors is
// SHA-256("infrix-root-history-v1" || be64(n) || treeHash), so what is anchored commits to the leaf count as well as the tree. The consumer of a bundle's leaf is the
// bundle's own outcome id: the leaf is the moment the node read its root to finalize THAT outcome, so the proof binds the bundle to the leaf with no slack.
//
// WHEN. The leaf's canonical height is the node's own statement. The check dates it from L0: it cannot be later than the last canonical height of the anchor batch that
// covers its seal, and it cannot be earlier than the first height of the PRIOR anchored window, which the document names with a CONSISTENCY PROOF (RFC 9162 section
// 2.1.4) that the prior seal's tree is a prefix of the covering one, so "this leaf was appended after the prior anchor" is a fact about one history and not about two.
// The lower edge is as tight as the prior the node names: a node may name an older anchor than the immediate predecessor and widen its own span, which loosens the
// bound and never falsifies it.
//
// THIS IS THE FOURTH IMPLEMENTATION, INDEPENDENT ON PURPOSE (the others are the node's pkg/rootaccum, which makes the proofs, infrix-verify's stateroot package, which
// verifykit uses, and @infrix/verify's, which the SDK ships). One file of vectors generated by the Infrix runtime pins all four: every leaf hash, the seal of every tree size to 40, every leaf's audit path, the
// consistency proof between every pair of sizes, the compact range of every tree size (the checkpoints) and a table of document cases, a tamper case per outcome of the rule
// below (testdata/state-root-vectors.json, SHA-256 pinned by test/stateRootAccumulator.test.mjs).
//
// THE RULE (the same in all four): no document SKIPS and leaves every verdict as it was; a version 1 document SKIPS ("no consumer recorded": it shows the root was held, not
// that THIS bundle read it) and so does a version it does not read, BEFORE the status is looked at (the order of the runtime's own Check); a document awaiting the next anchor
// or unavailable SKIPS with its reason; a proven one that names no consumer SKIPS; a bundle with no outcome id cannot be bound and SKIPS. A proven document is REFUSED when it was recorded for another consumer than the bundle's, when it
// is for another root than the bundle's, when the bundle carries no root, when its path does not compute to the seal it names (a document rewritten to name another
// consumer does not), when it names no anchor, and, given an L0 reader, when L0 does not list the seal. With no reader a consistent proof SKIPS. With a reader the leaf is
// dated: a covering entry with no window leaves it undated (SKIP); a leaf later than the covering window's last height is REFUSED; no prior anchor SKIPS by name; a prior
// that names no anchor, whose consistency proof does not show its tree is a prefix of the covering one, whose tree already holds the leaf, that L0 does not have or does
// not list, or whose window starts after the leaf, is REFUSED; a prior entry with no window SKIPS; within both windows it PASSES. It changes no assurance level.
//
// THE CHECKPOINT STATEMENT (ledger L1647). A node that checkpointed its root history dropped the leaves before the checkpoint, so a bundle recorded before it can only be
// proven by the document exported with it, and the node answers any other such bundle with an UNAVAILABLE document that carries its own statement of the checkpoint: the
// number of leaves sealed (size), the canonical height of the last (lastHeight), the sealed root over them (sealedRoot), the compact range of their tree (compact: the
// perfect subtrees of the binary decomposition of size, left to right) and, when it knows it, the L0 anchor of that seal. The statement proves NOTHING about the bundle, so it is
// never a pass; what it can be is FALSE, and a false one is REFUSED: the compact range must be the decomposition of size, fold (the last subtree, then each earlier one hashed
// over the rest) to the tree hash, and seal(size, hash) must be the sealed root it names. A statement that holds SKIPS saying so ("the bundle's state root is unchecked"); with an
// L0 reader and an anchor named, L0 must list the sealed root (a seal the node never anchored is REFUSED, an unreadable anchor is REFUSED), and a statement that names no anchor,
// or has no reader, SKIPS as unconfirmed. Only an unavailable document of a version this verifier reads is judged this way.
//
// The Verify view has NO L0 reader yet (the browser reads only the anchor transaction's block, see l0CrossCheck.js, not the batch entry's listed roots and canonical
// window), so every proven document it is given ends at the "no L0 endpoint was supplied" skip: the proof into the named seal and the binding to this bundle are
// checked, that the node anchored the seal is not, and the view says so. The L0 read is optional and injected: `reader.anchorAt(txHash)` resolves the anchor
// entry L0 holds, `{ roots, firstHeight, lastHeight }` (roots as Uint8Array(32) values or 64-character hex strings; both heights 0 or absent when the entry carries no
// canonical window), taken from L0 itself and never from the node that produced the bundle.

import { sha256, concatBytes, bytesToHex, bytesEqual, coerce32, isZero32 } from '/lib/canonicalJson.js';

export const STATE_ROOT_SEAL_DOMAIN = 'infrix-root-history-v1';
export const STATE_ROOT_CONSUMER_DOMAIN = 'infrix-root-consumer-v1';
export const STATE_ROOT_DOCUMENT_VERSION = 'infrix-state-root-proof-v2';
const STATE_ROOT_DOCUMENT_VERSION_V1 = 'infrix-state-root-proof-v1';
export const STATE_ROOT_DOCUMENT_KEY = 'stateRootProof';
export const STATE_ROOT_CHECK_NAME = 'state_root_accumulator';

const BAD_PROOF = 'the proof does not prove inclusion';
const enc = new TextEncoder();

function be64(n) {
  const out = new Uint8Array(8);
  new DataView(out.buffer).setBigUint64(0, BigInt(n), false);
  return out;
}

/** SHA-256(domain || utf8(id)): what a consumer leaf commits to. */
export async function consumerDigest(id) {
  return sha256(concatBytes(enc.encode(STATE_ROOT_CONSUMER_DOMAIN), enc.encode(id)));
}

/** The leaf hash of a root-change leaf (no consumer) or a consumer leaf. */
export async function stateRootLeafHash(height, root, consumer) {
  let data = concatBytes(concatBytes(Uint8Array.of(0x00), be64(height)), root);
  if (consumer) data = concatBytes(data, await consumerDigest(consumer));
  return sha256(data);
}

async function nodeHash(left, right) {
  return sha256(concatBytes(concatBytes(Uint8Array.of(0x01), left), right));
}

async function seal(size, treeHash) {
  return sha256(concatBytes(concatBytes(enc.encode(STATE_ROOT_SEAL_DOMAIN), be64(size)), treeHash));
}

/** The sealed root of a tree of `size` leaves with hash `treeHash`: what the node anchors. */
export const stateRootSeal = seal;

function decode32(hex) {
  if (typeof hex !== 'string' || !/^[0-9a-fA-F]*$/.test(hex) || hex.length % 2 !== 0) {
    throw new Error('not hex');
  }
  if (hex.length !== 64) throw new Error(`${hex.length / 2} bytes, want 32`);
  const out = new Uint8Array(32);
  for (let i = 0; i < 32; i++) out[i] = parseInt(hex.slice(2 * i, 2 * i + 2), 16);
  return out;
}

function decodePath(list) {
  const out = [];
  for (let i = 0; i < list.length; i++) {
    try {
      out.push(decode32(list[i]));
    } catch (e) {
      throw new Error(`[${i}]: ${e.message}`);
    }
  }
  return out;
}

const short = (h) => (h.length > 16 ? `${h.slice(0, 16)}...` : h);

/**
 * The sealed root an inclusion proof commits to, recomputed from its leaf and audit path alone (RFC 9162 section 2.1.3.2), for leaf number `index` of a tree of
 * `size` leaves. `consumer` is '' (or absent) for a root-change leaf. Throws for a path of the wrong length for that index and size.
 */
export async function sealedRootOf(index, size, height, root, consumer, path) {
  let fn = BigInt(index);
  let sn = BigInt(size) - 1n;
  if (BigInt(size) === 0n || BigInt(index) >= BigInt(size)) throw new Error(BAD_PROOF);
  let acc = await stateRootLeafHash(height, root, consumer);
  for (const sibling of path) {
    if (sn === 0n) throw new Error(BAD_PROOF);
    if ((fn & 1n) === 1n || fn === sn) {
      acc = await nodeHash(sibling, acc);
      while ((fn & 1n) === 0n && fn !== 0n) {
        fn >>= 1n;
        sn >>= 1n;
      }
    } else {
      acc = await nodeHash(acc, sibling);
    }
    fn >>= 1n;
    sn >>= 1n;
  }
  if (sn !== 0n) throw new Error(BAD_PROOF);
  return seal(size, acc);
}

/**
 * Verify an RFC 9162 section 2.1.4.2 consistency proof that the tree of `first` leaves with hash `firstHash` is a prefix of a tree of `second` leaves, and return the
 * hash of the second tree the proof computes. It does not decide that the second hash is the one anyone anchored: the caller compares the seal of it. Throws when the
 * proof does not verify.
 */
export async function verifyConsistency(first, second, firstHash, path) {
  const f = BigInt(first);
  const s = BigInt(second);
  if (f === 0n || f > s) throw new Error(BAD_PROOF);
  if (f === s) {
    if (path.length !== 0) throw new Error(BAD_PROOF);
    return firstHash;
  }
  let nodes = path;
  if ((f & (f - 1n)) === 0n) nodes = [firstHash, ...path]; // an exact power of two: the first tree's hash is the first node of the path
  if (nodes.length === 0) throw new Error(BAD_PROOF);
  let fn = f - 1n;
  let sn = s - 1n;
  while ((fn & 1n) === 1n) {
    fn >>= 1n;
    sn >>= 1n;
  }
  let fr = nodes[0];
  let sr = nodes[0];
  for (const c of nodes.slice(1)) {
    if (sn === 0n) throw new Error(BAD_PROOF);
    if ((fn & 1n) === 1n || fn === sn) {
      fr = await nodeHash(c, fr);
      sr = await nodeHash(c, sr);
      if ((fn & 1n) === 0n) {
        while ((fn & 1n) === 0n && fn !== 0n) {
          fn >>= 1n;
          sn >>= 1n;
        }
      }
    } else {
      sr = await nodeHash(sr, c);
    }
    fn >>= 1n;
    sn >>= 1n;
  }
  if (sn !== 0n || !bytesEqual(fr, firstHash)) throw new Error(BAD_PROOF);
  return sr;
}

const skip = (detail) => ({ verdict: 'skip', detail });
const fail = (detail) => ({ verdict: 'fail', detail });

const asBytes = (r) => (typeof r === 'string' ? decode32(r) : r);
const lists = (entry, sealed) => (entry.roots ?? []).some((r) => bytesEqual(asBytes(r), sealed));
const hasWindow = (entry) => BigInt(entry.firstHeight ?? 0) !== 0n || BigInt(entry.lastHeight ?? 0) !== 0n;

/** An anchor entry from a reader: `anchorAt` (the entry with its window), or `rootsAt` (roots only, so every window is absent and the leaf is undated). */
async function readAnchor(reader, txHash) {
  if (typeof reader.anchorAt === 'function') return reader.anchorAt(txHash);
  return { roots: await reader.rootsAt(txHash), firstHeight: 0, lastHeight: 0 };
}

const wholeNumber = (n) => {
  if (typeof n === 'bigint' && n >= 0n) return n;
  if (typeof n === 'number' && Number.isSafeInteger(n) && n >= 0) return BigInt(n);
  throw new Error('not a whole number');
};

/**
 * Check a checkpoint statement against itself (ledger L1647): `{ size, sealedRoot, compact }`. The compact range must be the decomposition of `size` (the perfect subtrees of
 * its binary decomposition, left to right: as many entries as `size` has one bits) and fold to the tree hash the sealed root commits to together with `size`. A statement that
 * fails names a range for another tree, or a seal for another size. Throws an Error naming what is wrong; resolves when the statement holds.
 */
export async function verifyStateRootCheckpoint(c) {
  let size;
  try {
    size = wholeNumber(c.size);
  } catch (e) {
    throw new Error(`size: ${e.message}`);
  }
  if (size === 0n) throw new Error('the checkpoint seals no leaves');
  let sealed;
  try {
    sealed = decode32(c.sealedRoot);
  } catch (e) {
    throw new Error(`sealedRoot: ${e.message}`);
  }
  const compact = c.compact ?? [];
  if (!Array.isArray(compact)) throw new Error('compact: not a list');
  const nodes = [];
  let rest = size;
  for (let i = 0; i < compact.length; i++) {
    if (rest === 0n) throw new Error(`the compact range has more entries than the ${size} leaves it covers have subtrees`);
    try {
      nodes.push(decode32(compact[i]));
    } catch (e) {
      throw new Error(`compact[${i}]: ${e.message}`);
    }
    rest -= 1n << BigInt(rest.toString(2).length - 1); // the largest power of two in what is left: the next perfect subtree
  }
  if (rest !== 0n) {
    const want = size.toString(2).replace(/0/g, '').length;
    throw new Error(`a tree of ${size} leaves has a compact range of ${want} subtrees, not ${nodes.length}`);
  }
  let acc = nodes[nodes.length - 1];
  for (let i = nodes.length - 2; i >= 0; i--) acc = await nodeHash(nodes[i], acc);
  if (!bytesEqual(await seal(size, acc), sealed)) throw new Error('the compact range does not fold to the sealed root');
}

/**
 * Judge the checkpoint an UNAVAILABLE document states (ledger L1647). The statement proves nothing about the bundle (a skip at best, never a pass): what it can be is FALSE, and
 * a false one is a failure. With an L0 reader and an anchor named, L0 must list the sealed root.
 */
async function checkCheckpointStatement(doc, reader) {
  const c = doc.checkpoint;
  try {
    await verifyStateRootCheckpoint(c);
  } catch (e) {
    return fail(`the node states it checkpointed its root history at leaf ${c.size}, and the statement is false: ${e.message}`);
  }
  const base = `the node could not prove the bundle's state root: ${doc.reason ?? ''}; it states its root history was checkpointed at leaf ${c.size} (canonical height ${c.lastHeight ?? 0}): the checkpoint's compact range folds to sealed root ${short(c.sealedRoot)}, and the bundle's state root is unchecked`;
  if (!reader) {
    return skip(`${base}, but no L0 endpoint was supplied, so that the node anchored that seal is not independently confirmed`);
  }
  if (!c.anchor || !c.anchor.txHash) {
    return skip(`${base}, but the statement names no L0 anchor for that seal, so it is unconfirmed`);
  }
  let anchored;
  try {
    anchored = await readAnchor(reader, c.anchor.txHash);
  } catch (e) {
    return fail(`could not read the checkpoint's anchor from L0: ${e.message}`);
  }
  if (!lists(anchored, decode32(c.sealedRoot))) {
    return fail(`the checkpoint's sealed root ${short(c.sealedRoot)} is not listed in the L0 anchor entry of transaction ${short(c.anchor.txHash)}: the node never anchored it`);
  }
  return skip(`${base}, and L0 lists that seal in anchor transaction ${short(c.anchor.txHash)}`);
}

/**
 * Judge a bundle's state root against the document an export attached beside the package.
 * @param {object|null|undefined} doc the stateRootProof document (null/undefined: none attached)
 * @param {Uint8Array} bundleRoot the bundle's own state root (32 bytes)
 * @param {string} consumerId the bundle's own outcome id: the consumer its leaf must have been recorded for ('' when the bundle names none)
 * @param {{anchorAt(txHash: string): Promise<{roots: Array<Uint8Array|string>, firstHeight?: number, lastHeight?: number}>}|null} [reader] reads the anchor entry L0 holds; null/undefined: no L0 endpoint
 * @returns {Promise<{verdict: 'pass'|'fail'|'skip', detail: string}>}
 */
export async function checkStateRootProof(doc, bundleRoot, consumerId, reader) {
  if (doc === null || doc === undefined) {
    return skip('no state root proof is attached to this bundle: its state root is unchecked (bundles exported before the node kept a root history carry none)');
  }
  // the version first, as the runtime's Check reads it: a document of a form this verifier does not read is never looked into, whatever its status says
  if (doc.version === STATE_ROOT_DOCUMENT_VERSION_V1) {
    return skip(
      "the attached state root proof is version 1, which records no consumer: it shows the root was held but not that this bundle read it, so no consumer recorded, and the bundle's state root is unchecked",
    );
  }
  if (doc.version !== STATE_ROOT_DOCUMENT_VERSION) {
    return skip(`the attached state root proof is version "${doc.version}", which this verifier does not read: the bundle's state root is unchecked`);
  }
  switch (doc.status) {
    case 'awaiting_anchor':
      return skip(
        `finalized after the newest anchor: the bundle's state root is in the node's history (leaf at canonical height ${doc.leafHeight ?? 0}, history now ${doc.currentSize ?? 0} leaves) but the newest anchored seal covers only ${doc.newestAnchoredSize ?? 0}, so it is unchecked until the next anchor; re-export or re-attach the proof then`,
      );
    case 'unavailable':
      if (doc.checkpoint !== undefined && doc.checkpoint !== null) return checkCheckpointStatement(doc, reader);
      return skip(`the node could not prove the bundle's state root: ${doc.reason ?? ''}`);
    case 'proven':
      break;
    default:
      return skip(`the attached state root proof has status "${doc.status}", which this verifier does not read: the bundle's state root is unchecked`);
  }
  if (!doc.consumer) {
    return skip("the attached state root proof names no consumer (no consumer recorded): it cannot be bound to this bundle, so the bundle's state root is unchecked");
  }
  if (!consumerId) {
    return skip("the bundle names no outcome id, so there is no consumer to bind the proof to: the bundle's state root is unchecked");
  }
  if (doc.consumer !== consumerId) {
    return fail(`the leaf was recorded for "${doc.consumer}", which is not this bundle's ("${consumerId}"): the proof is for another consumption`);
  }
  if (isZero32(bundleRoot)) {
    return fail('a state root proof is attached to a bundle that carries no state root');
  }
  let leafRoot;
  try {
    leafRoot = decode32(doc.stateRoot);
  } catch (e) {
    return fail(`the attached state root proof is malformed: stateRoot: ${e.message}`);
  }
  let path;
  try {
    path = decodePath(doc.path ?? []);
  } catch (e) {
    return fail(`the attached state root proof is malformed: path${e.message}`);
  }
  if (!bytesEqual(leafRoot, bundleRoot)) {
    return fail(`the proof is for state root ${doc.stateRoot} but the bundle carries ${bytesToHex(bundleRoot)}`);
  }
  let named;
  try {
    named = decode32(doc.accumulatorRoot);
  } catch (e) {
    return fail(`the attached state root proof names a malformed accumulator root: ${e.message}`);
  }
  let computed = null;
  let why = BAD_PROOF;
  try {
    computed = await sealedRootOf(doc.leafIndex ?? 0, doc.treeSize ?? 0, doc.leafHeight ?? 0, leafRoot, doc.consumer, path);
  } catch (e) {
    why = e.message;
  }
  if (computed === null || !bytesEqual(computed, named)) {
    return fail(`the bundle's state root does not prove into the accumulator root the document names (${doc.accumulatorRoot}): ${why}`);
  }
  if (!reader) {
    return skip(
      `the bundle's state root proves into accumulator root ${short(doc.accumulatorRoot)} (leaf ${doc.leafIndex ?? 0} of ${doc.treeSize ?? 0}, recorded for this bundle), but no L0 endpoint was supplied, so that the node anchored that root is not independently confirmed`,
    );
  }
  if (!doc.anchor || !doc.anchor.txHash) {
    return fail('the attached state root proof names no L0 anchor transaction for its accumulator root');
  }
  let cover;
  try {
    cover = await readAnchor(reader, doc.anchor.txHash);
  } catch (e) {
    return fail(`could not read the accumulator anchor from L0: ${e.message}`);
  }
  if (!lists(cover, named)) {
    return fail(`the accumulator root ${short(doc.accumulatorRoot)} is not listed in the L0 anchor entry of transaction ${short(doc.anchor.txHash)}: the node never anchored it`);
  }
  if (!hasWindow(cover)) {
    return skip(
      `the bundle's state root is leaf ${doc.leafIndex ?? 0} of ${doc.treeSize ?? 0} in the node's root history and L0 lists its seal, but the covering entry carries no canonical window, so the leaf's height is undated`,
    );
  }
  const leafHeight = BigInt(doc.leafHeight ?? 0);
  const coverLast = BigInt(cover.lastHeight ?? 0);
  if (leafHeight > coverLast) {
    return fail(`the leaf's canonical height ${leafHeight} is after the last height ${coverLast} of the anchor batch that covers its seal: a leaf cannot be recorded after the anchor that covers it`);
  }
  const p = doc.prior;
  if (!p) {
    return skip(
      `the bundle's state root is leaf ${doc.leafIndex ?? 0} of ${doc.treeSize ?? 0} in the node's root history, bound to this bundle, and its seal is listed by L0 with the leaf at or before canonical height ${coverLast}, but the document names no earlier anchor, so it is unchecked: no earlier anchored window to date it from`,
    );
  }
  if (!p.anchor || !p.anchor.txHash) {
    return fail('the prior anchor names no L0 anchor transaction (prior anchor names no L0 anchor transaction)');
  }
  let priorRoot;
  let priorMth;
  let consistency;
  try {
    priorRoot = decode32(p.accumulatorRoot);
  } catch (e) {
    return fail(`the prior anchor names a malformed accumulator root: ${e.message}`);
  }
  try {
    priorMth = decode32(p.mth);
  } catch (e) {
    return fail(`the prior anchor names a malformed tree hash: ${e.message}`);
  }
  try {
    consistency = decodePath(p.consistency ?? []);
  } catch (e) {
    return fail(`the prior anchor's consistency proof is malformed: ${e.message}`);
  }
  if (!bytesEqual(await seal(p.treeSize ?? 0, priorMth), priorRoot)) {
    return fail("the prior anchor's tree size and tree hash are not the ones its sealed root commits to: the prior tree is not shown to be a prefix of the covering one");
  }
  let coverMth = null;
  try {
    coverMth = await verifyConsistency(p.treeSize ?? 0, doc.treeSize ?? 0, priorMth, consistency);
  } catch {
    coverMth = null;
  }
  if (coverMth === null || !bytesEqual(await seal(doc.treeSize ?? 0, coverMth), named)) {
    return fail(
      `the prior tree (${p.treeSize ?? 0} leaves) is not shown to be a prefix of the covering tree (${doc.treeSize ?? 0} leaves): the consistency proof does not verify against the two sealed roots`,
    );
  }
  if (BigInt(doc.leafIndex ?? 0) < BigInt(p.treeSize ?? 0)) {
    return fail(`the leaf (number ${doc.leafIndex ?? 0}) is inside the prior anchor's tree of ${p.treeSize ?? 0} leaves: it was recorded before the prior anchor, so the prior cannot date it from below`);
  }
  let prior;
  try {
    prior = await readAnchor(reader, p.anchor.txHash);
  } catch (e) {
    return fail(`could not read the prior accumulator anchor from L0: ${e.message}`);
  }
  if (!lists(prior, priorRoot)) {
    return fail(`the prior accumulator root ${short(p.accumulatorRoot)} is not listed in the L0 anchor entry of transaction ${short(p.anchor.txHash)}: the node never anchored it`);
  }
  if (!hasWindow(prior)) {
    return skip("the prior anchor's entry carries no canonical window, so there is no earlier anchored window to date it from: the leaf is bounded from above only");
  }
  const priorFirst = BigInt(prior.firstHeight ?? 0);
  if (leafHeight < priorFirst) {
    return fail(`the leaf's canonical height ${leafHeight} is before the first height ${priorFirst} of the prior anchor's window: it is not in the span the two anchors enclose`);
  }
  return {
    verdict: 'pass',
    detail: `the bundle's state root is leaf ${doc.leafIndex ?? 0} of ${doc.treeSize ?? 0} in the node's root history, recorded for this bundle, whose sealed root ${short(doc.accumulatorRoot)} L0 lists in anchor transaction ${short(doc.anchor.txHash)}; the leaf at canonical height ${leafHeight} lies inside the span [${priorFirst}, ${coverLast}] that sealed root and the prior anchor ${short(p.anchor.txHash)} (whose tree the covering one extends) enclose`,
  };
}

function bundleOf(pkg) {
  return typeof pkg.bundleData === 'string' ? JSON.parse(pkg.bundleData) : pkg.bundleData;
}

/**
 * The state root of an exported package, read from its embedded bundle (a 32-element number array or a hex string, as the package encodes it).
 */
export function bundleStateRoot(pkg) {
  return coerce32(bundleOf(pkg).stateRoot);
}

/**
 * The consumer id of an exported package: the bundle's own outcome id (inside the bundle hash), '' when the bundle names none.
 */
export function bundleConsumerId(pkg) {
  const id = bundleOf(pkg).outcomeId;
  return typeof id === 'string' ? id : '';
}

/**
 * The state_root_accumulator check of an exported file: the package (bare, or under "bundle") and the sibling `stateRootProof` document beside it.
 * `options.require` turns every skip into a failure (a verifier that accepts only a bundle whose state root is proven).
 */
export async function verifyStateRootOfExport(file, reader, options = {}) {
  const pkg = file.bundleData !== undefined ? file : file.bundle;
  let result;
  try {
    result = await checkStateRootProof(file[STATE_ROOT_DOCUMENT_KEY], bundleStateRoot(pkg), bundleConsumerId(pkg), reader);
  } catch (e) {
    result = fail(`the bundle's state root could not be read: ${e.message}`);
  }
  if (options.require && result.verdict === 'skip') {
    result = fail(`a proven state root is required but it is not: ${result.detail}`);
  }
  return { name: STATE_ROOT_CHECK_NAME, ...result };
}

/**
 * Append the state_root_accumulator check of an exported file to a portable-package verification result, as the Verify view shows it: a failure fails the verification
 * and a skip is shown as unchecked and leaves the verdict where it was (a file with no sibling document is a skip). `reader` is null in the browser today.
 * @param {{passed: boolean, checks: Array<object>}} result the result of verifyPortablePackage
 * @param {object} file the pasted export file: the package, bare or under "bundle", with the sibling stateRootProof document when the node attached one
 */
export async function appendStateRootCheck(result, file, reader = null, options = {}) {
  const sr = await verifyStateRootOfExport(file, reader, options);
  const row = {
    name: sr.name,
    passed: sr.verdict !== 'fail',
    detail: sr.verdict === 'skip' ? `unchecked: ${sr.detail}` : sr.detail,
  };
  return { passed: result.passed && row.passed, checks: [...result.checks, row] };
}
